import type { Agent } from "../spec";
import type { Harness, Tool } from "../vocab";

/** What a harness can guarantee for a given feature. */
export type Support = "enforce" | "approximate" | "unsupported";

export type Feature =
  | "tool_allowlist" // only listed tools are available
  | "mcp_deny" // MCP tools are unavailable unless allowed
  | "skill_access" // listed skills are available to the agent
  | "skill_restrict" // unlisted skills are unavailable
  | "model_select"; // the agent can pin a model

export interface GeneratedFile {
  /** Path relative to the harness's install root, e.g. "agents/reviewer.md". */
  path: string;
  content: string;
}

export interface CompileResult {
  files: GeneratedFile[];
  warnings: string[];
  /** Reasons this agent cannot be installed on this harness in strict mode. */
  errors: string[];
}

export interface Adapter {
  name: Harness;
  /** Display name. */
  label: string;
  /**
   * False until the adapter's output has passed contract tests against the
   * real harness. Install prints a warning for unverified adapters.
   */
  verified: boolean;
  capabilities: Record<Feature, Support>;
  /** Native tool name(s) for each agentc tool. Missing = harness has no equivalent. */
  toolMap: Partial<Record<Tool, string[]>>;
  /** User-level root this harness reads agents and skills from. */
  installRoot(): string;
  /** Subfolders under installRoot() that agentc manages. */
  managedDirs: { agents: string; skills: string };
  /** Is the harness present on this machine? */
  detect(): boolean;
  /** Fails if something the harness needs to spawn agents is missing. */
  preflight?(): string | null;
  compile(agent: Agent): CompileResult;
}

export function header(agent: Agent): string {
  return `Generated by agentc from ${agent.sourcePath}\nDo not edit: change the source and run \`agentc install\`.`;
}

/**
 * Checks shared by every adapter: features the agent needs vs what the harness
 * can enforce, and tools with no native equivalent.
 */
export function checkRequirements(adapter: Adapter, agent: Agent): { errors: string[]; warnings: string[] } {
  const errors: string[] = [];
  const warnings: string[] = [];
  const cap = adapter.capabilities;

  // Hard requirements: tool restrictions are the point of agentc.
  if (cap.tool_allowlist !== "enforce") errors.push(`${adapter.label} cannot enforce a tool allowlist (${cap.tool_allowlist})`);
  if (cap.mcp_deny !== "enforce") errors.push(`${adapter.label} cannot block MCP tools (${cap.mcp_deny})`);

  const missing = agent.tools.filter((t) => !adapter.toolMap[t]?.length);
  if (missing.length) errors.push(`${adapter.label} has no equivalent for tool(s): ${missing.join(", ")}`);

  if (agent.model[adapter.name] && cap.model_select === "unsupported")
    errors.push(`${adapter.label} agents cannot pin a model; remove model.${adapter.name}`);

  // Skills: best effort, warned. Whether "approximate" is acceptable is still an open design question.
  if (agent.skills.length) {
    if (cap.skill_access === "unsupported")
      warnings.push(`${adapter.label} cannot attach skills to this agent; skills ${agent.skills.join(", ")} are installed but may not reach it`);
    if (cap.skill_restrict !== "enforce")
      warnings.push(`${adapter.label} cannot stop this agent from using other installed skills (${cap.skill_restrict})`);
  }

  return { errors, warnings };
}

export function nativeTools(adapter: Adapter, tools: Tool[]): string[] {
  const out: string[] = [];
  for (const t of tools) for (const n of adapter.toolMap[t] ?? []) if (!out.includes(n)) out.push(n);
  return out;
}
